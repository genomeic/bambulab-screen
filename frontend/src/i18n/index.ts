import { createI18n } from 'vue-i18n'

export type AppLocale = 'zh' | 'en'
export type LocalePreference = 'auto' | AppLocale

const LOCALE_STORAGE_KEY = 'app_locale'

const detectLocale = (): AppLocale => {
  if (typeof navigator === 'undefined') return 'zh'
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const getLocalePreference = (): LocalePreference => {
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY)
    if (stored === 'zh' || stored === 'en' || stored === 'auto') return stored
  } catch {}
  return 'auto'
}

export const setLocalePreference = (pref: LocalePreference) => {
  localStorage.setItem(LOCALE_STORAGE_KEY, pref)
}

const resolveLocale = (): AppLocale => {
  const pref = getLocalePreference()
  if (pref === 'auto') return detectLocale()
  return pref
}

